        /// <summary>The year, month and day a version went out, or false when that row has no day.</summary>
        public static bool Try(int order, out int year, out int month, out int day)
        {
            for (int i = 0; i < Days.Length; i += 4)
            {
                if (Days[i] == order)
                {
                    year = Days[i + 1];
                    month = Days[i + 2];
                    day = Days[i + 3];
                    return true;
                }
            }
            year = 0;
            month = 0;
            day = 0;
            return false;
        }

        private static readonly string[] MonthKeys =
        {
            "reallife_calendar_month_1", "reallife_calendar_month_2", "reallife_calendar_month_3",
            "reallife_calendar_month_4", "reallife_calendar_month_5", "reallife_calendar_month_6",
            "reallife_calendar_month_7", "reallife_calendar_month_8", "reallife_calendar_month_9",
            "reallife_calendar_month_10", "reallife_calendar_month_11", "reallife_calendar_month_12"
        };

        /// <summary>The day as the Guide prints it. The month comes from the caller's words. Null when the row has no day.</summary>
        public static string Words(int order, Func<string, string> text)
        {
            if (!Try(order, out int year, out int month, out int day) || text == null || month < 1 || month > 12)
            {
                return null;
            }
            string monthName = text(MonthKeys[month - 1]);
            return day.ToString(CultureInfo.InvariantCulture) + " " + monthName + " " + year.ToString(CultureInfo.InvariantCulture);
        }

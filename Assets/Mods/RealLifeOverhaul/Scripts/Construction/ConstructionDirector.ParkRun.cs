using System;
using System.Collections.Generic;
using System.Globalization;
using UI.Notification;
using UnityEngine;

namespace RealLifeOverhaul.Construction
{
    /// <summary>A business or rival near a car park, as the game shows it: its name, who, how much it wants bays (1 to 10) and how far off.</summary>
    public struct ParkNeighbour
    {
        public string Name;
        public int Who;        // CarParkLease.Business or CarParkLease.Rival
        public int Weight;     // 1 to 10: its size
        public int Metres;
    }

    /// <summary>
    /// Car parks at work (docs/features/construction.md, "Parking lots"): each game hour a public car park is as full as its site's custom,
    /// the hour, the day, its price and the other public bays near it make it (CarParkRules.Cars), a leased one as its lessees' cars are;
    /// the game's own cars are left to park in the bays by that share (the lane's chance of a free spot, regenerated by the game's own
    /// queue when the player is far); each night the day's takings are paid into the game's books as their own line with the upkeep
    /// against them, the street rate the player's own cars were charged for standing in their lot is paid back, and a lease is paid on
    /// the day its term ends. Each week offers come from the businesses and rivals near. COST: nothing per frame; an hour's pass over
    /// the few car parks, a day's pass and a week's look at the buildings near each.
    /// </summary>
    public sealed partial class ConstructionDirector
    {
        private sealed class ParkRound
        {
            public int Day = -1;
            public int Nearby, RivalBays, Traffic, Level, CarShare, Fair, District;
        }

        private readonly Dictionary<int, ParkRound> _parkRound = new Dictionary<int, ParkRound>(8);
        private readonly List<ParkNeighbour> _parkNear = new List<ParkNeighbour>(32);
        private readonly Dictionary<int, CarParkWorld> _parkWorlds = new Dictionary<int, CarParkWorld>(8);
        private static readonly int[] DistrictCars = { 900, 850 };   // the thousandths of a district's people who drive (DistrictSplit's cars on its streets)

        // ------------------------------------------------------------------ what is round a car park

        private ParkRound ParkAround(CarParkFile c, int day)
        {
            if (!_parkRound.TryGetValue(c.Id, out ParkRound r))
            {
                r = new ParkRound();
                _parkRound[c.Id] = r;
            }
            if (r.Day == day)
            {
                return r;
            }
            r.Day = day;
            r.Fair = ParkFair(c.Lot);
            r.District = DistrictOfLot(c.Lot);
            r.CarShare = DistrictCars[BuildCatalogue.Clamp(r.District, 0, DistrictCars.Length - 1)];
            Func<int, int> level = BuildModeBridges.MarketLevel;
            r.Level = level != null ? BuildCatalogue.Clamp(level(r.District), 500, 1500) : 1000;
            r.Nearby = 0;
            r.RivalBays = 0;
            r.Traffic = 20;
            if (!ParkGround(c, out LotView site))
            {
                return r;
            }
            r.Traffic = site.Traffic;
            var at = new Vector3(site.X, site.Y, site.Z);
            ConstructionGame.ParkNeighbours(at, CarParkRules.ReachMetres, _parkNear);
            r.Nearby = Math.Min(CarParkRules.NearbyMost, _parkNear.Count);
            for (int i = 0; i < _state.CarParks.Count; i++)
            {
                CarParkFile o = _state.CarParks[i];
                if (o == c || !o.Standing || o.Mode != CarParkMode.Public || (o.Owner == CarParkOwner.Builder && GoingPublic.InSession) || !ParkGround(o, out LotView there))
                {
                    continue;
                }
                float dx = there.X - site.X, dz = there.Z - site.Z;
                if (dx * dx + dz * dz <= (float)CarParkRules.RivalReachMetres * CarParkRules.RivalReachMetres)
                {
                    r.RivalBays += o.Bays;
                }
            }
            return r;
        }

        // ------------------------------------------------------------------ the hour

        private void ParkHour(int day, int hour)
        {
            if (!ParkingOn || _state.CarParks.Count == 0)
            {
                return;
            }
            bool weekend = LandRules.Weekday(day) >= 5;
            int stamp = day * 24 + hour;
            for (int i = 0; i < _state.CarParks.Count; i++)
            {
                CarParkFile c = _state.CarParks[i];
                if (!c.Standing || c.Seen == stamp || (c.Owner == CarParkOwner.Builder && GoingPublic.InSession))
                {
                    continue;
                }
                c.Seen = stamp;
                ParkRound r = ParkAround(c, day);
                int cars;
                if (c.Mode == CarParkMode.Public)
                {
                    cars = CarParkRules.Cars(c.Bays, hour, weekend, CarParkRules.Catchment(r.Traffic, r.Nearby), r.RivalBays, c.Price, r.Fair, r.CarShare, r.Level, _state.Seed, c.Id, day);
                    if (c.Owner == CarParkOwner.Player)
                    {
                        c.Taken += CarParkRules.Takings(cars, c.Price);
                    }
                }
                else
                {
                    cars = CarParkRules.LeaseCars(c.Leased + (c.Owner == CarParkOwner.Builder ? c.Others : 0), hour, weekend);
                }
                c.Cars = Math.Min(c.Bays, cars);
                c.Own += ParkOwnCars(c);
                ParkFill(c);
            }
        }

        // The player's own cars standing in a lot of theirs, or in bays they lease at a lot of the city's: car-hours the game charged its street rate for.
        private int ParkOwnCars(CarParkFile c)
        {
            int allowed = c.Owner == CarParkOwner.Player ? c.Bays : c.LeasedByPlayer;
            if (allowed <= 0 || !ParkGround(c, out LotView site))
            {
                return 0;
            }
            return Math.Min(allowed, ConstructionGame.PlayerCarsIn(site.X, site.Z, site.Yaw, site.Width, site.Depth));
        }

        // The game's cars in a car park's bays follow the hour's share: the lane's chance of a free spot is the rest.
        private void ParkFill(CarParkFile c)
        {
            if (_parkWorlds.TryGetValue(c.Id, out CarParkWorld world))
            {
                CarParkGame.Fill(world, 100 - CarParkRules.Occupied(c.Cars, c.Bays));
            }
        }

        // ------------------------------------------------------------------ the day

        private void ParkDay(int day)
        {
            if (!ParkingOn)
            {
                return;
            }
            for (int i = 0; i < _state.CarParks.Count; i++)
            {
                CarParkFile c = _state.CarParks[i];
                if (!c.Standing)
                {
                    continue;
                }
                if (c.Owner == CarParkOwner.Player)
                {
                    ParkAccounts(c, day);
                }
                ParkLeasesDay(c, day);
            }
            ParkProjectsDay(day);
            ParkNpcDay(day);
            ParkWorldSecond();
        }

        // The day that has ended: its takings into the game's books, the upkeep against them, the street rate the player's own cars were charged paid back.
        private void ParkAccounts(CarParkFile c, int day)
        {
            long cents = c.Taken;
            c.Taken = 0;
            long income = cents / 100L, upkeep = CarParkRules.Upkeep(c.Bays, c.Mode, ConstructionGame.Prices), refund = 0L;
            string name = ParkName(c);
            if (income > 0L)
            {
                ConstructionGame.Give(income, "reallife_transaction_park_income", name);
                c.Earned += income * 100L;
            }
            if (upkeep > 0L)
            {
                ConstructionGame.Force(upkeep, "reallife_transaction_park_upkeep", name, true);
                c.Spent += upkeep * 100L;
            }
            if (c.Own > 0)
            {
                refund = CarParkRules.OwnFee(c.Own, ConstructionGame.ParkingRate(DistrictKeyOf(DistrictOfLot(c.Lot))));
                if (refund > 0L)
                {
                    ConstructionGame.Give(refund, "reallife_transaction_park_refund", name);
                    _state.ParkRefunded += refund * 100L;
                }
                c.Own = 0;
            }
            long accrual = c.Mode == CarParkMode.Lease ? c.LeaseIncome / 100L / CarParkRules.LeaseDays : 0L;
            long net = income + refund + accrual - upkeep;
            c.AddDay(day - 1, (int)Math.Max(int.MinValue, Math.Min(int.MaxValue, net)));
            if (Verbose)
            {
                Logger?.Info("Construction check (car park " + c.Id + ", day " + (day - 1) + "): " + c.Bays + " bays, " + c.Mode + ", taken " + income + ", upkeep " + upkeep
                             + ", the street rate paid back " + refund
                             + ", net " + net + ": PASS.");
            }
        }

        // The leases of a car park paid on the day their term ends, the offers that ran out let go, and each week the offers that came.
        private void ParkLeasesDay(CarParkFile c, int day)
        {
            for (int i = c.Leases.Count - 1; i >= 0; i--)
            {
                CarParkLease l = c.Leases[i];
                if (day <= l.PaidTo)
                {
                    continue;
                }
                long month = l.Monthly * l.Bays / 100L;
                if (c.Owner == CarParkOwner.Player)
                {
                    if (l.Ending || c.Mode != CarParkMode.Lease)
                    {
                        c.Leases.RemoveAt(i);
                        ParkTellLease("reallife_park_notice_lease_over", c, l);
                        continue;
                    }
                    ConstructionGame.Give(month, "reallife_transaction_park_lease_income", ParkName(c));
                    c.Earned += month * 100L;
                    l.PaidTo += CarParkRules.LeaseDays;
                    continue;
                }
                if (l.Who == CarParkLease.Player)
                {
                    if (l.Ending || !ConstructionGame.Take(month, "reallife_transaction_park_lease", ParkName(c), true))
                    {
                        c.Leases.RemoveAt(i);
                        ParkTellLease(l.Ending ? "reallife_park_notice_lease_over" : "reallife_park_notice_lease_unpaid", c, l);
                        continue;
                    }
                    l.PaidTo += CarParkRules.LeaseDays;
                    _state.PayOut(month, day);
                }
            }
            for (int i = c.Offers.Count - 1; i >= 0; i--)
            {
                if (day > c.Offers[i].Expires)
                {
                    c.Offers.RemoveAt(i);
                }
            }
            if (c.Owner == CarParkOwner.Player && c.Mode == CarParkMode.Lease && !GoingPublic.InSession && day % 7 == c.Id % 7)
            {
                ParkOffersWeek(c, day);
            }
        }

        // A week's looks from the businesses and rivals within reach: each asks by its size and the lot's traffic, for bays at a price about the usual.
        private void ParkOffersWeek(CarParkFile c, int day)
        {
            ParkRound r = ParkAround(c, day);
            if (!ParkGround(c, out LotView site))
            {
                return;
            }
            ConstructionGame.ParkNeighbours(new Vector3(site.X, site.Y, site.Z), CarParkRules.ReachMetres, _parkNear);   // this car park's own: the day's cache holds the last one looked at
            ParkOffersFrom(c, day, r, _parkNear, false);
        }

        // The offers of the businesses and rivals given, each asking by its size and the lot's traffic (always, for a test).
        private void ParkOffersFrom(CarParkFile c, int day, ParkRound r, List<ParkNeighbour> near, bool always)
        {
            int week = day / 7;
            int taken = 0;
            for (int i = 0; i < c.Offers.Count; i++)
            {
                taken += c.Offers[i].Bays;
            }
            for (int i = 0; i < near.Count && c.Offers.Count < CarParkRules.OffersMost; i++)
            {
                ParkNeighbour n = near[i];
                if (ParkHasName(c, n.Name))
                {
                    continue;
                }
                int who = BuildRandom.Hash(n.Name);
                BuildRandom random = BuildRandom.Of(_state.Seed, c.Id * 53 + week, who);
                if (!always && !random.Chance(CarParkRules.AskChance(n.Weight, r.Traffic)))
                {
                    continue;
                }
                int bays = CarParkRules.OfferBays(n.Weight, c.Free - taken, _state.Seed, c.Id, week, who);
                if (bays < CarParkRules.LeaseBaysLeast)
                {
                    continue;
                }
                var offer = new CarParkOffer
                {
                    Id = _state.NewId(), Name = n.Name, Who = n.Who, Bays = bays, Monthly = CarParkRules.LeaseOffer(r.Fair, _state.Seed, c.Id, week, who), Expires = day + CarParkRules.OfferDays
                };
                c.Offers.Add(offer);
                taken += bays;
                ParkTellOffer(c, offer);
                Logger?.Info("Construction: car park " + c.Id + " has an offer from " + n.Name + " (" + (n.Who == CarParkLease.Rival ? "a rival" : "a business") + ", " + n.Metres
                             + " m off) for " + bays + " bays at "
                             + offer.Monthly + " cents a bay a month, standing until day " + offer.Expires + ".");
            }
        }

        private static bool ParkHasName(CarParkFile c, string name)
        {
            for (int i = 0; i < c.Leases.Count; i++)
            {
                if (string.Equals(c.Leases[i].Name, name, StringComparison.Ordinal))
                {
                    return true;
                }
            }
            for (int i = 0; i < c.Offers.Count; i++)
            {
                if (string.Equals(c.Offers[i].Name, name, StringComparison.Ordinal))
                {
                    return true;
                }
            }
            return false;
        }

        private void ParkTellOffer(CarParkFile c, CarParkOffer o)
        {
            var data = new Dictionary<string, string>(5)
            {
                { "name", ParkName(c) }, { "who", o.Name }, { "bays", o.Bays.ToString(CultureInfo.InvariantCulture) },
                { "amount", ConstructionText.Money(o.Monthly * o.Bays / 100L) }
            };
            int id = c.Id;
            ConstructionGame.Tell(NotificationType.Info, "reallife_park_notice_offer", data, () => ParkDesk(id));
        }

        private void ParkTellLease(string key, CarParkFile c, CarParkLease l)
        {
            var data = new Dictionary<string, string>(4)
            {
                { "name", ParkName(c) }, { "who", string.IsNullOrEmpty(l.Name) ? ConstructionText.T("reallife_park_lessee_you") : l.Name }, { "bays", l.Bays.ToString(CultureInfo.InvariantCulture) }
            };
            int id = c.Id;
            ConstructionGame.Tell(NotificationType.Info, key, data, () => ParkDesk(id));
        }

        // ------------------------------------------------------------------ what the player does with a car park

        /// <summary>A car park of the player's let publicly or by the month; ends its leases (the unused days paid back) when it goes public. Returns a text key, or null.</summary>
        public string ParkSetMode(CarParkFile c, CarParkMode mode)
        {
            if (c == null || c.Owner != CarParkOwner.Player || !c.Standing)
            {
                return "reallife_park_answer_not_yours";
            }
            if (GoingPublic.InSession)
            {
                return "reallife_bld_answer_session_land";
            }
            if (c.Mode == mode)
            {
                return null;
            }
            if (mode == CarParkMode.Public)
            {
                ParkEndLeases(c, ConstructionGame.Day);
            }
            c.Mode = mode;
            c.Offers.Clear();
            c.Seen = -1;   // the next hour is worked afresh
            Changed();
            Logger?.Info("Construction: car park " + c.Id + " is now let " + mode + ".");
            return null;
        }

        // Every lease ended at once, the days left of each month paid back to its lessee out of the player's purse.
        private void ParkEndLeases(CarParkFile c, int day)
        {
            long back = 0L;
            for (int i = c.Leases.Count - 1; i >= 0; i--)
            {
                CarParkLease l = c.Leases[i];
                if (l.Who != CarParkLease.Player)
                {
                    back += CarParkRules.Refund(l.Monthly, l.Bays, Math.Max(0, l.PaidTo - day + 1)) / 100L;
                }
                c.Leases.RemoveAt(i);
            }
            if (back > 0L)
            {
                ConstructionGame.Force(back, "reallife_transaction_park_lease_back", ParkName(c), true);
                c.Spent += back * 100L;
            }
        }

        /// <summary>The price an hour put a step up or down inside the band. Returns the new price in cents.</summary>
        public int ParkStepPrice(CarParkFile c, int direction)
        {
            if (c == null || c.Owner != CarParkOwner.Player || GoingPublic.InSession)
            {
                return c != null ? c.Price : 0;
            }
            c.Price = CarParkRules.Stepped(c.Price, ParkFair(c.Lot), direction);
            Changed();
            return c.Price;
        }

        /// <summary>An offer accepted: the lease begins, its first month paid at once. Returns a text key, or null.</summary>
        public string ParkAccept(CarParkFile c, int offerId)
        {
            CarParkOffer o = null;
            for (int i = 0; c != null && i < c.Offers.Count; i++)
            {
                o = c.Offers[i].Id == offerId ? c.Offers[i] : o;
            }
            if (o == null || c.Owner != CarParkOwner.Player || c.Mode != CarParkMode.Lease)
            {
                return "reallife_park_answer_no_offer";
            }
            if (o.Bays > c.Free || c.Leases.Count >= CarParkRules.LeasesMost)
            {
                return "reallife_park_answer_no_room";
            }
            int day = ConstructionGame.Day;
            long month = o.Monthly * o.Bays / 100L;
            ConstructionGame.Give(month, "reallife_transaction_park_lease_income", ParkName(c));
            c.Earned += month * 100L;
            c.Leases.Add(new CarParkLease { Id = _state.NewId(), Name = o.Name, Who = o.Who, Bays = o.Bays, Monthly = o.Monthly, Start = day, PaidTo = day + CarParkRules.LeaseDays - 1 });
            c.Offers.Remove(o);
            Changed();
            Logger?.Info("Construction: car park " + c.Id + " leased " + o.Bays + " bays to " + o.Name + " at " + o.Monthly + " cents a bay a month from day " + day + ".");
            return null;
        }

        /// <summary>An offer turned down. Returns a text key, or null.</summary>
        public string ParkDecline(CarParkFile c, int offerId)
        {
            for (int i = 0; c != null && i < c.Offers.Count; i++)
            {
                if (c.Offers[i].Id == offerId)
                {
                    c.Offers.RemoveAt(i);
                    Changed();
                    return null;
                }
            }
            return "reallife_park_answer_no_offer";
        }

        /// <summary>A lease marked not to be renewed: its lessee stays until the term's end. Returns a text key, or null.</summary>
        public string ParkEnd(CarParkFile c, int leaseId)
        {
            for (int i = 0; c != null && i < c.Leases.Count; i++)
            {
                if (c.Leases[i].Id == leaseId)
                {
                    c.Leases[i].Ending = true;
                    Changed();
                    return null;
                }
            }
            return "reallife_park_answer_no_lease";
        }

        /// <summary>The bays the player may lease at a car park of the city's now: all that are free where it lets leases, a fifth of its bays where it lets the hour.</summary>
        public int ParkLeaseRoom(CarParkFile c)
        {
            if (c == null || c.Owner != CarParkOwner.Builder || !c.Standing || GoingPublic.InSession)
            {
                return 0;
            }
            int room = c.Mode == CarParkMode.Lease ? c.Free : Math.Max(0, c.Bays / 5 - c.LeasedByPlayer);
            return Math.Max(0, Math.Min(room, CarParkRules.LeaseBaysMost - c.LeasedByPlayer));
        }

        /// <summary>The usual price of a bay a month at a car park of the city's this week, in cents.</summary>
        public long ParkLeasePrice(CarParkFile c)
        {
            return CarParkRules.LeaseOffer(ParkFair(c.Lot), _state.Seed, c.Id, ConstructionGame.Day / 7, 9973);
        }

        /// <summary>Bays leased at a car park of the city's, the first month paid at once. Returns a text key, or null.</summary>
        public string ParkLeaseFrom(CarParkFile c, int bays)
        {
            if (c == null || c.Owner != CarParkOwner.Builder || !c.Standing)
            {
                return "reallife_park_answer_not_theirs";
            }
            if (GoingPublic.InSession)
            {
                return "reallife_bld_answer_session_land";
            }
            if (bays < 1 || bays > ParkLeaseRoom(c) || c.Leases.Count >= CarParkRules.LeasesMost)
            {
                return "reallife_park_answer_no_room";
            }
            long price = ParkLeasePrice(c), month = price * bays / 100L;
            int day = ConstructionGame.Day;
            if (!ConstructionGame.Take(month, "reallife_transaction_park_lease", ParkName(c), true))
            {
                return "reallife_bld_answer_no_money";
            }
            _state.PayOut(month, day);
            c.Leases.Add(new CarParkLease
            {
                Id = _state.NewId(), Name = string.Empty, Who = CarParkLease.Player, Bays = bays, Monthly = price, Start = day, PaidTo = day + CarParkRules.LeaseDays - 1
            });
            Changed();
            Logger?.Info("Construction: the player leased " + bays + " bays at car park " + c.Id + " (" + ParkOwnerName(c) + ") at " + price + " cents a bay a month from day " + day + ".");
            return null;
        }

        /// <summary>A car park of the player's closed: its leases ended with the unused days paid back, its land free for a building again, its bays and lamps taken away.</summary>
        public string ParkClose(CarParkFile c)
        {
            if (c == null || c.Owner != CarParkOwner.Player || c.Stage == CarParkStage.Closed)
            {
                return "reallife_park_answer_not_yours";
            }
            if (GoingPublic.InSession)
            {
                return "reallife_bld_answer_session_land";
            }
            ParkEndLeases(c, ConstructionGame.Day);
            c.Stage = CarParkStage.Closed;
            ParkWorldGone(c.Id);
            LotFile land = _state.Lot(c.Lot);
            if (land != null)
            {
                land.EmptySince = ConstructionGame.Day;   // bare land again: the vacant land tax counts from today
            }
            ParksChanged();
            Paper("reallife_park_paper_closed", ParkName(c), 0);
            Logger?.Info("Construction: car park " + c.Id + " closed.");
            Changed();
            return null;
        }

        // ------------------------------------------------------------------ plans: parking provided by a car park of the player's near a new building

        /// <summary>Bays of the player's car parks (and bays they lease) within reach of a project's ground that its building's plans may count as the parking they ask for.</summary>
        public int ParkSpare(ProjectFile p)
        {
            if (p == null || _state == null || _state.CarParks.Count == 0 || !ParkingOn || !Lot(p.Lot ?? string.Empty, out LotView mine))
            {
                return 0;
            }
            int spare = 0;
            for (int i = 0; i < _state.CarParks.Count; i++)
            {
                CarParkFile c = _state.CarParks[i];
                if (!c.Standing || (c.Owner == CarParkOwner.Builder && c.LeasedByPlayer <= 0) || !ParkGround(c, out LotView there))
                {
                    continue;
                }
                float dx = there.X - mine.X, dz = there.Z - mine.Z;
                if (dx * dx + dz * dz > (float)CarParkRules.NearMetres * CarParkRules.NearMetres)
                {
                    continue;
                }
                spare += c.Owner == CarParkOwner.Builder ? c.LeasedByPlayer : c.Mode == CarParkMode.Lease ? c.Free : c.Bays / 2;
            }
            return spare;
        }

        /// <summary>True when a car park of the player's near a project covers the parking its plans ask for.</summary>
        public bool ParkCovers(ProjectFile p)
        {
            return p != null && p.ParkingNeeded > 0 && ParkSpare(p) >= p.ParkingNeeded;
        }
    }

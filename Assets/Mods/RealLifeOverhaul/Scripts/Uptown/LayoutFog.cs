        /// <summary>uv0.y for a uv0.x, on the game's own path between its edge, ring and far values; the shader reads x alone.</summary>
        public static float UvY(float u)
        {
            if (u <= RingU)
            {
                return EdgeV + (RingV - EdgeV) * (u / RingU);
            }
            float t = (u - RingU) / (FarU - RingU);
            return RingV + (FarV - RingV) * (t < 1f ? t : 1f);
        }

        /// <summary>uv1 at a point of the mesh's own space: the game's planar projection.</summary>
        public static float PlanarU(float x)
        {
            return (PlanarX - x) / PlanarWidth;
        }

        public static float PlanarV(float z)
        {
            return (z - PlanarZ) / PlanarWidth;
        }
